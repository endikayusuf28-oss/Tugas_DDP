import math

def keliling_lingkaran(r):
    hasil = 2 * math.pi * r
    print("keliling lingkaran r =", r, "adalah", hasil)

def keliling_persegi(s):
    hasil = 4 * s
    print("keliling persegi sisi =", s, "adalah", hasil)

def keliling_segitiga(a, b, c):
    hasil = a + b + c
    print("keliling segitiga", a, b, c, "adalah", hasil)